"""Cuentas de DepaRent (una sola para inquilinos y propietarios), guardadas en SQLite o en Postgres.

Como propietario: sus departamentos, su publicación y los interesados. Como inquilino: su perfil de búsqueda
(cuestionario del modelo 7) y los departamentos que guardó.

Prototipo: las contraseñas se guardan con PBKDF2-SHA256 y sal propia, y los tokens de sesión solo
como hash. En local la base vive en data/deparent.sqlite (no se sube a GitHub); DEPARENT_DB permite cambiarla.
En producción DATABASE_URL apunta a un Postgres externo (Neon), porque el disco de Render se borra en cada despliegue.
"""
import hashlib
import hmac
import json
import os
import re
import secrets
import sqlite3
import time
from pathlib import Path

from modelo import ROOT

BASE = Path(os.environ.get("DEPARENT_DB", ROOT / "data/deparent.sqlite"))
DATABASE_URL = os.environ.get("DATABASE_URL")
ITERACIONES = 200_000
DURACION_SESION_S = 7 * 24 * 3600
PATRON_EMAIL = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
ESQUEMA = """
CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER PRIMARY KEY, nombre TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
    sal BLOB NOT NULL, hash BLOB NOT NULL, creado REAL NOT NULL);
CREATE TABLE IF NOT EXISTS sesiones (
    token_hash TEXT PRIMARY KEY, usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    expira REAL NOT NULL);
CREATE TABLE IF NOT EXISTS departamentos (
    id INTEGER PRIMARY KEY, usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    nombre TEXT NOT NULL, vivienda TEXT NOT NULL, latitud REAL, longitud REAL, resumen TEXT,
    precio_publicado REAL, escenario_publicado TEXT, publicado_en REAL,
    creado REAL NOT NULL, actualizado REAL NOT NULL);
CREATE TABLE IF NOT EXISTS interesados (
    id INTEGER PRIMARY KEY, departamento_id INTEGER NOT NULL REFERENCES departamentos(id) ON DELETE CASCADE,
    nombre TEXT NOT NULL, email TEXT NOT NULL, mensaje TEXT NOT NULL, creado REAL NOT NULL);
CREATE TABLE IF NOT EXISTS perfiles_inquilino (
    id INTEGER PRIMARY KEY, usuario_id INTEGER NOT NULL UNIQUE REFERENCES usuarios(id) ON DELETE CASCADE,
    perfil TEXT NOT NULL, actualizado REAL NOT NULL);
CREATE TABLE IF NOT EXISTS guardados (
    id INTEGER PRIMARY KEY, usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    anuncio_id TEXT NOT NULL, datos TEXT NOT NULL, creado REAL NOT NULL, UNIQUE (usuario_id, anuncio_id));
"""
# Mismas tablas en Postgres: REAL ahí es de 4 bytes y no alcanza para time.time(), por eso DOUBLE PRECISION.
ESQUEMA_PG = (ESQUEMA.replace("id INTEGER PRIMARY KEY", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
              .replace("INTEGER", "BIGINT").replace("BLOB", "BYTEA").replace("REAL", "DOUBLE PRECISION"))

try:
    import psycopg
    from psycopg.rows import dict_row
    ERRORES_INTEGRIDAD = (sqlite3.IntegrityError, psycopg.IntegrityError)
except ImportError:  # En local basta SQLite; psycopg solo hace falta con DATABASE_URL.
    psycopg = None
    ERRORES_INTEGRIDAD = (sqlite3.IntegrityError,)


class DatosInvalidos(ValueError):
    pass


class NoAutorizado(Exception):
    pass


class NoEncontrado(Exception):
    pass


class SinPermiso(Exception):
    pass


class _Resultado:
    def __init__(self, cursor, lastrowid=None):
        self._cursor, self.lastrowid = cursor, lastrowid

    def fetchone(self):
        return self._cursor.fetchone()

    def __iter__(self):
        return iter(self._cursor)


class _Postgres:
    """Envuelve psycopg con la parte de la interfaz de sqlite3 que usa este módulo: execute con «?»,
    lastrowid tras un INSERT, filas accesibles por nombre y «with conexion:» como transacción."""
    esquema_listo = False

    def __init__(self, url):
        self._conexion = psycopg.connect(url, row_factory=dict_row, autocommit=True)
        self._transacciones = []
        if not _Postgres.esquema_listo:
            self._conexion.execute(ESQUEMA_PG)
            _Postgres.esquema_listo = True

    def execute(self, sql, parametros=()):
        sql = sql.replace("?", "%s")
        if sql.startswith("INSERT") and not sql.startswith("INSERT INTO sesiones"):
            cursor = self._conexion.execute(sql + " RETURNING id", parametros)
            return _Resultado(cursor, cursor.fetchone()["id"])
        return _Resultado(self._conexion.execute(sql, parametros))

    def __enter__(self):
        self._transacciones.append(self._conexion.transaction())
        self._transacciones[-1].__enter__()
        return self

    def __exit__(self, *error):
        return self._transacciones.pop().__exit__(*error)

    def close(self):
        self._conexion.close()


def conectar(base=None):
    if DATABASE_URL and base is None:
        return _Postgres(DATABASE_URL)
    ruta = Path(base or BASE)
    ruta.parent.mkdir(parents=True, exist_ok=True)
    # Cada petición abre y cierra su propia conexión, pero FastAPI puede crearla y usarla en hilos distintos.
    conexion = sqlite3.connect(ruta, check_same_thread=False)
    conexion.row_factory = sqlite3.Row
    conexion.execute("PRAGMA foreign_keys = ON")
    conexion.executescript(ESQUEMA)
    return conexion


def _hash_password(password, sal):
    return hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), sal, ITERACIONES)


def _hash_token(token):
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def es_analista(email):
    """Los analistas se definen por correo en DEPARENT_ANALISTAS (separados por comas), no en la base:
    así no hace falta migrar la tabla de usuarios de Neon ni dar el rol desde la propia app."""
    lista = {e.strip().lower() for e in os.environ.get("DEPARENT_ANALISTAS", "").split(",") if e.strip()}
    return (email or "").strip().lower() in lista


def _usuario(fila):
    return {"id": fila["id"], "nombre": fila["nombre"], "email": fila["email"],
            "rol": "analista" if es_analista(fila["email"]) else "usuario"}


def registrar(conexion, nombre, email, password):
    nombre, email = (nombre or "").strip(), (email or "").strip().lower()
    if not 2 <= len(nombre) <= 80:
        raise DatosInvalidos("Escribe tu nombre (entre 2 y 80 caracteres).")
    if not PATRON_EMAIL.match(email) or len(email) > 120:
        raise DatosInvalidos("Escribe un correo válido.")
    if len(password or "") < 8:
        raise DatosInvalidos("La contraseña debe tener al menos 8 caracteres.")
    sal = secrets.token_bytes(16)
    try:
        with conexion:
            cursor = conexion.execute("INSERT INTO usuarios (nombre, email, sal, hash, creado) VALUES (?, ?, ?, ?, ?)",
                                      (nombre, email, sal, _hash_password(password, sal), time.time()))
    except ERRORES_INTEGRIDAD:
        raise DatosInvalidos("Ya existe una cuenta con ese correo.")
    return {"id": cursor.lastrowid, "nombre": nombre, "email": email, "rol": "analista" if es_analista(email) else "usuario"}


def ingresar(conexion, email, password):
    fila = conexion.execute("SELECT * FROM usuarios WHERE email = ?", ((email or "").strip().lower(),)).fetchone()
    # Se calcula el hash aunque el correo no exista, para no revelar qué correos están registrados.
    sal = fila["sal"] if fila else b"\0" * 16
    calculado = _hash_password(password or "", sal)
    if fila is None or not hmac.compare_digest(calculado, fila["hash"]):
        raise NoAutorizado("Correo o contraseña incorrectos.")
    return _usuario(fila)


def crear_sesion(conexion, usuario_id):
    token = secrets.token_urlsafe(32)
    with conexion:
        conexion.execute("DELETE FROM sesiones WHERE expira < ?", (time.time(),))
        conexion.execute("INSERT INTO sesiones VALUES (?, ?, ?)", (_hash_token(token), usuario_id, time.time() + DURACION_SESION_S))
    return token


def usuario_de_token(conexion, token):
    if not token:
        raise NoAutorizado("Inicia sesión para continuar.")
    fila = conexion.execute("SELECT u.* FROM sesiones s JOIN usuarios u ON u.id = s.usuario_id "
                            "WHERE s.token_hash = ? AND s.expira > ?", (_hash_token(token), time.time())).fetchone()
    if fila is None:
        raise NoAutorizado("Tu sesión expiró. Inicia sesión de nuevo.")
    return _usuario(fila)


def cerrar_sesion(conexion, token):
    with conexion:
        conexion.execute("DELETE FROM sesiones WHERE token_hash = ?", (_hash_token(token or ""),))


def _departamento(fila):
    return {"id": fila["id"], "nombre": fila["nombre"], "vivienda": json.loads(fila["vivienda"]),
            "ubicacion": ({"latitud": fila["latitud"], "longitud": fila["longitud"]} if fila["latitud"] is not None else None),
            "resumen": json.loads(fila["resumen"]) if fila["resumen"] else None,
            "publicacion": ({"precio_soles": fila["precio_publicado"], "escenario": fila["escenario_publicado"],
                             "desde": fila["publicado_en"]} if fila["precio_publicado"] is not None else None),
            "creado": fila["creado"], "actualizado": fila["actualizado"]}


def _validar_nombre_departamento(nombre):
    nombre = (nombre or "").strip()
    if not 2 <= len(nombre) <= 80:
        raise DatosInvalidos("Ponle un nombre al departamento (entre 2 y 80 caracteres), por ejemplo «Depa de Lince».")
    return nombre


def listar_departamentos(conexion, usuario_id):
    filas = conexion.execute("SELECT * FROM departamentos WHERE usuario_id = ? ORDER BY actualizado DESC", (usuario_id,))
    return [_departamento(f) for f in filas]


def obtener_departamento(conexion, usuario_id, departamento_id):
    fila = conexion.execute("SELECT * FROM departamentos WHERE id = ? AND usuario_id = ?", (departamento_id, usuario_id)).fetchone()
    if fila is None:
        raise NoEncontrado("No encontramos ese departamento en tu cuenta.")
    return _departamento(fila)


def guardar_departamento(conexion, usuario_id, nombre, vivienda, ubicacion, resumen, departamento_id=None):
    """Crea o actualiza. Cambiar las características retira la publicación, porque su precio ya no aplica."""
    nombre = _validar_nombre_departamento(nombre)
    lat, lon = (ubicacion["latitud"], ubicacion["longitud"]) if ubicacion else (None, None)
    ahora = time.time()
    with conexion:
        if departamento_id is None:
            cursor = conexion.execute(
                "INSERT INTO departamentos (usuario_id, nombre, vivienda, latitud, longitud, resumen, creado, actualizado) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                (usuario_id, nombre, json.dumps(vivienda), lat, lon, json.dumps(resumen), ahora, ahora))
            departamento_id = cursor.lastrowid
        else:
            anterior = obtener_departamento(conexion, usuario_id, departamento_id)
            cambio = anterior["vivienda"] != vivienda
            conexion.execute(
                "UPDATE departamentos SET nombre = ?, vivienda = ?, latitud = ?, longitud = ?, resumen = ?, actualizado = ?"
                + (", precio_publicado = NULL, escenario_publicado = NULL, publicado_en = NULL" if cambio else "")
                + " WHERE id = ? AND usuario_id = ?",
                (nombre, json.dumps(vivienda), lat, lon, json.dumps(resumen), ahora, departamento_id, usuario_id))
    return obtener_departamento(conexion, usuario_id, departamento_id)


def eliminar_departamento(conexion, usuario_id, departamento_id):
    obtener_departamento(conexion, usuario_id, departamento_id)
    with conexion:
        conexion.execute("DELETE FROM departamentos WHERE id = ? AND usuario_id = ?", (departamento_id, usuario_id))


def publicar(conexion, usuario_id, departamento_id, precio, escenario):
    obtener_departamento(conexion, usuario_id, departamento_id)
    if precio is None:
        with conexion:
            conexion.execute("UPDATE departamentos SET precio_publicado = NULL, escenario_publicado = NULL, publicado_en = NULL "
                             "WHERE id = ? AND usuario_id = ?", (departamento_id, usuario_id))
    else:
        if not 300 <= float(precio) <= 50000:
            raise DatosInvalidos("El precio de publicación debe estar entre S/ 300 y S/ 50,000.")
        with conexion:
            conexion.execute("UPDATE departamentos SET precio_publicado = ?, escenario_publicado = ?, publicado_en = ? "
                             "WHERE id = ? AND usuario_id = ?",
                             (round(float(precio), 2), (escenario or "Personalizado")[:40], time.time(), departamento_id, usuario_id))
    return obtener_departamento(conexion, usuario_id, departamento_id)


def publicados(conexion):
    """Departamentos publicados por cualquier propietario, sin datos de contacto del dueño."""
    filas = conexion.execute("SELECT * FROM departamentos WHERE precio_publicado IS NOT NULL ORDER BY publicado_en DESC")
    return [_departamento(f) for f in filas]


def publicado(conexion, departamento_id):
    """Un departamento publicado tal como lo ve un inquilino: con el nombre de pila del propietario, sin su correo."""
    fila = conexion.execute("SELECT d.*, u.nombre AS propietario FROM departamentos d JOIN usuarios u ON u.id = d.usuario_id "
                            "WHERE d.id = ? AND d.precio_publicado IS NOT NULL", (departamento_id,)).fetchone()
    if fila is None:
        raise NoEncontrado("Ese departamento no está publicado.")
    return {**_departamento(fila), "propietario": fila["propietario"].split()[0]}


def registrar_interes(conexion, departamento_id, nombre, email, mensaje):
    publicado(conexion, departamento_id)
    nombre, email, mensaje = (nombre or "").strip(), (email or "").strip().lower(), (mensaje or "").strip()
    if not 2 <= len(nombre) <= 80:
        raise DatosInvalidos("Escribe tu nombre (entre 2 y 80 caracteres).")
    if not PATRON_EMAIL.match(email) or len(email) > 120:
        raise DatosInvalidos("Escribe un correo válido para que el propietario pueda responderte.")
    if not 5 <= len(mensaje) <= 600:
        raise DatosInvalidos("Escribe un mensaje de entre 5 y 600 caracteres.")
    with conexion:
        conexion.execute("INSERT INTO interesados (departamento_id, nombre, email, mensaje, creado) VALUES (?, ?, ?, ?, ?)",
                         (departamento_id, nombre, email, mensaje, time.time()))


def listar_interesados(conexion, usuario_id, departamento_id):
    obtener_departamento(conexion, usuario_id, departamento_id)
    filas = conexion.execute("SELECT nombre, email, mensaje, creado FROM interesados WHERE departamento_id = ? ORDER BY creado DESC",
                             (departamento_id,))
    return [dict(f) for f in filas]


# ---------- Inquilino: perfil de búsqueda y guardados ----------

PATRON_ANUNCIO = re.compile(r"^[md]\d{1,12}$")


def obtener_perfil(conexion, usuario_id):
    fila = conexion.execute("SELECT perfil, actualizado FROM perfiles_inquilino WHERE usuario_id = ?", (usuario_id,)).fetchone()
    return None if fila is None else {**json.loads(fila["perfil"]), "actualizado": fila["actualizado"]}


def guardar_perfil(conexion, usuario_id, perfil):
    """perfil ya validado por recomendador.validar_perfil; reemplaza el anterior."""
    with conexion:
        conexion.execute("INSERT INTO perfiles_inquilino (usuario_id, perfil, actualizado) VALUES (?, ?, ?) "
                         "ON CONFLICT (usuario_id) DO UPDATE SET perfil = excluded.perfil, actualizado = excluded.actualizado",
                         (usuario_id, json.dumps(perfil, ensure_ascii=False), time.time()))
    return obtener_perfil(conexion, usuario_id)


def _validar_anuncio(anuncio_id):
    if not PATRON_ANUNCIO.match(str(anuncio_id or "")):
        raise NoEncontrado("No encontramos ese anuncio.")


def listar_guardados(conexion, usuario_id):
    filas = conexion.execute("SELECT anuncio_id, datos, creado FROM guardados WHERE usuario_id = ? ORDER BY creado DESC, id DESC",
                             (usuario_id,))
    return [{**json.loads(f["datos"]), "id": f["anuncio_id"], "guardado": f["creado"]} for f in filas]


def guardar_anuncio(conexion, usuario_id, anuncio_id, datos):
    """Guarda una copia de cómo se veía el anuncio: sigue visible aunque salga del mercado en otra captura."""
    _validar_anuncio(anuncio_id)
    with conexion:
        conexion.execute("INSERT INTO guardados (usuario_id, anuncio_id, datos, creado) VALUES (?, ?, ?, ?) "
                         "ON CONFLICT (usuario_id, anuncio_id) DO UPDATE SET datos = excluded.datos",
                         (usuario_id, anuncio_id, json.dumps(datos, ensure_ascii=False), time.time()))
    return listar_guardados(conexion, usuario_id)


def quitar_guardado(conexion, usuario_id, anuncio_id):
    _validar_anuncio(anuncio_id)
    with conexion:
        conexion.execute("DELETE FROM guardados WHERE usuario_id = ? AND anuncio_id = ?", (usuario_id, anuncio_id))
    return listar_guardados(conexion, usuario_id)


# ---------- KPIs del producto (solo analistas) ----------

def kpis_producto(conexion, ahora=None):
    """Conteos de uso del producto, sin datos personales: cuántas cuentas, perfiles, departamentos, guardados y mensajes."""
    ahora = ahora or time.time()
    semana = ahora - 7 * 24 * 3600
    uno = lambda sql, *p: list(dict(conexion.execute(sql, p).fetchone()).values())[0] or 0
    usuarios = uno("SELECT COUNT(*) AS n FROM usuarios")
    perfiles = uno("SELECT COUNT(*) AS n FROM perfiles_inquilino")
    con_guardados = uno("SELECT COUNT(DISTINCT usuario_id) AS n FROM guardados")
    propietarios = uno("SELECT COUNT(DISTINCT usuario_id) AS n FROM departamentos")
    departamentos = uno("SELECT COUNT(*) AS n FROM departamentos")
    publicados_n = uno("SELECT COUNT(*) AS n FROM departamentos WHERE precio_publicado IS NOT NULL")
    con_interes = uno("SELECT COUNT(DISTINCT departamento_id) AS n FROM interesados")
    tasa = lambda a, b: round(100 * a / b, 1) if b else None
    filas_precio = conexion.execute("SELECT precio_publicado, resumen FROM departamentos WHERE precio_publicado IS NOT NULL")
    diferencias = []
    for f in filas_precio:
        resumen = json.loads(f["resumen"]) if f["resumen"] else {}
        esperado = resumen.get("precio_estimado_soles")
        if esperado:
            diferencias.append(100 * (f["precio_publicado"] - esperado) / esperado)
    return {
        "usuarios": usuarios,
        "usuarios_nuevos_7_dias": uno("SELECT COUNT(*) AS n FROM usuarios WHERE creado >= ?", semana),
        "perfiles_completados": perfiles,
        "tasa_perfil_porcentaje": tasa(perfiles, usuarios),
        "guardados": uno("SELECT COUNT(*) AS n FROM guardados"),
        "usuarios_con_guardados": con_guardados,
        "tasa_perfil_a_guardado_porcentaje": tasa(con_guardados, perfiles),
        "propietarios": propietarios,
        "departamentos": departamentos,
        "departamentos_publicados": publicados_n,
        "tasa_publicacion_porcentaje": tasa(publicados_n, departamentos),
        "publicados_a_precio_propio": uno("SELECT COUNT(*) AS n FROM departamentos WHERE escenario_publicado = 'Personalizado'"),
        "diferencia_media_publicado_vs_esperado_porcentaje": round(sum(diferencias) / len(diferencias), 1) if diferencias else None,
        "mensajes_interesados": uno("SELECT COUNT(*) AS n FROM interesados"),
        "mensajes_7_dias": uno("SELECT COUNT(*) AS n FROM interesados WHERE creado >= ?", semana),
        "publicados_con_interes": con_interes,
        "tasa_publicado_con_interes_porcentaje": tasa(con_interes, publicados_n),
    }
